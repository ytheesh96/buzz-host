#!/usr/bin/env node
// Bundles Buzz's own Attention code (format, validation, object contract,
// tools and wake prompts) from a buzz-app checkout into server/attention-core.mjs,
// so remote agents behave exactly as local ones. Rerun after a Buzz update:
//
//   node attention/build-core.mjs [path-to-buzz-app]     default ~/Work/buzz-app
//
// Uses buzz-app's own Rolldown. Records the buzz-app commit in the output.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(process.argv[2] ?? path.join(os.homedir(), "Work/buzz-app"));
const src = (file) => JSON.stringify(path.join(app, "src", file));
const commit = execFileSync("git", ["-C", app, "log", "-1", "--format=%h %cs"]).toString().trim();
const dirty = execFileSync("git", ["-C", app, "status", "--porcelain", "--", "src"]).toString().trim();
if (dirty) throw new Error(`buzz-app has uncommitted changes under src/:\n${dirty}`);

const entry = path.join(os.tmpdir(), `buzz-host-attention-entry-${process.pid}.ts`);
fs.writeFileSync(
  entry,
  `export { ATTENTION_SCHEMA, validateObject, parseSlug, interestSlug, watchSlug, watchMatches, addressedTo, CHAT_KINDS, timerState, timerSpent, interestPaused, attentionOf, describeWatch, every, interestTitle } from ${src("features/agents/attention.ts")};
export { ABSENT, MIN_INTERVAL_SECS, AGENT_BYTES, AttentionError, objectAt, token, show, interestIds, watchSummaries, checkedWrite } from ${src("features/agents/attention-objects.ts")};
export { setAttention, withProgress } from ${src("features/agents/store.ts")};
export { ATTENTION_TOOLS, isAttentionTool, callAttentionTool } from ${src("buzz-mcp/attention.ts")};
export { ATTENTION_REVIEW, ATTENTION_NONE, ATTENTION_OFF, timerPrompt, watchPrompt, catchUpPrompt, CATCH_UP_TEXT_LIMIT } from ${src("features/agent-harness/attention-prompt.ts")};
export { readWindow, delivered, admitted, finished, heardOf, streamsOf, streamKey, undelivered, oldestFirst, inStream, CATCH_UP_PAGE, CATCH_UP_PAGES, CATCH_UP_BYTES, POLL_OVERLAP } from ${src("features/agents/catch-up.ts")};
export { CHANNEL_KINDS } from ${src("features/relay/channel-kinds.ts")};
`,
);

const rolldownDir = fs
  .readdirSync(path.join(app, "node_modules/.pnpm"))
  .find((name) => /^rolldown@\d/.test(name));
if (!rolldownDir) throw new Error("buzz-app has no rolldown; run pnpm install there");
const { build } = await import(
  pathToFileURL(path.join(app, "node_modules/.pnpm", rolldownDir, "node_modules/rolldown/dist/index.mjs")).href
);
const out = path.join(here, "../server/attention-core.mjs");
try {
  await build({
    input: entry,
    platform: "node",
    treeshake: true,
    write: true,
    output: {
      file: out,
      format: "esm",
      // catch-up.ts reaches Buzz's relay module, which has dynamic imports.
      codeSplitting: false,
      banner: `// GENERATED by attention/build-core.mjs from buzz-app ${commit}. Do not edit.\n// Buzz's own Attention code (block/buzz-app, Apache-2.0), bundled for buzz-host.`,
    },
  });
} finally {
  fs.rmSync(entry, { force: true });
}
console.log(`wrote ${path.relative(process.cwd(), out)} from buzz-app ${commit} (${fs.statSync(out).size} bytes)`);

// Schnorr signing for the relay watcher's NIP-42 login: @noble/curves, pinned
// to the version buzz-app installs, bundled with its @noble/hashes.
const pnpm = path.join(app, "node_modules/.pnpm");
const noble = fs.readdirSync(pnpm).find((name) => /^@noble\+curves@2\./.test(name));
if (!noble) throw new Error("buzz-app has no @noble/curves 2.x");
const nobleVersion = noble.split("@").pop();
const nobleDir = path.join(pnpm, noble, "node_modules/@noble");
const nobleEntry = path.join(nobleDir, "curves", `.buzz-host-entry-${process.pid}.js`);
fs.writeFileSync(
  nobleEntry,
  `export { schnorr } from "./secp256k1.js";\nexport { sha256 } from "@noble/hashes/sha2.js";\nexport { bytesToHex, hexToBytes } from "@noble/hashes/utils.js";\n`,
);
const nobleOut = path.join(here, "../server/noble.mjs");
try {
  await build({
    input: nobleEntry,
    platform: "node",
    treeshake: true,
    write: true,
    output: {
      file: nobleOut,
      format: "esm",
      banner: `// GENERATED by attention/build-core.mjs: @noble/curves ${nobleVersion} (schnorr, secp256k1) and\n// @noble/hashes (sha256), by Paul Miller, MIT License. Do not edit.`,
    },
  });
} finally {
  fs.rmSync(nobleEntry, { force: true });
}
console.log(`wrote ${path.relative(process.cwd(), nobleOut)} (@noble/curves ${nobleVersion}, ${fs.statSync(nobleOut).size} bytes)`);
