#!/usr/bin/env node
// Bundles plugin source files into self-contained ESM files Buzz loads.
// Uses buzz-app's Rolldown, matching attention/build-core.mjs, memory/build-nip44.mjs,
// plugin/build-markdown.mjs, and plugin/build-novnc.mjs.
//
//   node plugin/build.mjs [--check] [path-to-buzz-app]
//
// Targets:
//   - Remote Agents: plugin/src/index.js -> plugin/plugin.js
//   - Viewport: plugins/viewport/src/index.js -> plugins/viewport/plugin.js
//   - Hive Watch: plugins/hive-watch/src/index.js -> plugins/hive-watch/plugin.js
//
// Pass --check to verify all bundles match source without writing.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const appArg = args.find((a) => !a.startsWith("-"));
const app = path.resolve(appArg ?? process.env.BUZZ_APP ?? path.join(os.homedir(), "Work/buzz-app"));

const pnpm = path.join(app, "node_modules", ".pnpm");
if (!fs.existsSync(pnpm)) {
  throw new Error(`buzz-app node_modules not found at ${pnpm}; pass [path-to-buzz-app] or set BUZZ_APP`);
}
const rolldownDir = fs.readdirSync(pnpm).find((name) => /^rolldown@\d/.test(name));
if (!rolldownDir) throw new Error("buzz-app has no rolldown; run pnpm install there");
const { build } = await import(
  pathToFileURL(path.join(pnpm, rolldownDir, "node_modules/rolldown/dist/index.mjs")).href
);

const targets = [
  {
    name: "Remote Agents",
    entry: path.join(here, "src", "index.js"),
    out: path.join(here, "plugin.js"),
    banner: [
      "// GENERATED by plugin/build.mjs from plugin/src/. Do not edit directly;",
      "// edit files under plugin/src/ and run `node plugin/build.mjs`.",
    ].join("\n"),
  },
  {
    name: "Viewport",
    entry: path.join(root, "plugins", "viewport", "src", "index.js"),
    out: path.join(root, "plugins", "viewport", "plugin.js"),
    banner: [
      "// GENERATED by plugin/build.mjs from plugins/viewport/src/ and plugin/src/. Do not edit directly;",
      "// edit source files and run `node plugin/build.mjs`.",
    ].join("\n"),
  },
  {
    name: "Hive Watch",
    entry: path.join(root, "plugins", "hive-watch", "src", "index.js"),
    out: path.join(root, "plugins", "hive-watch", "plugin.js"),
    banner: [
      "// GENERATED by plugin/build.mjs from plugins/hive-watch/src/ and plugin/src/. Do not edit directly;",
      "// edit source files and run `node plugin/build.mjs`.",
    ].join("\n"),
  },
];

let outOfDate = false;

for (const target of targets) {
  const result = await build({
    input: target.entry,
    platform: "browser",
    treeshake: true,
    write: false,
    output: {
      format: "esm",
      codeSplitting: false,
      minify: false,
      banner: target.banner,
    },
  });

  const code = result.output[0].code;
  if (/\bfrom\s*["']\.?\.\//.test(code)) {
    throw new Error(`bundled ${target.name} (${path.relative(root, target.out)}) still contains relative imports`);
  }

  if (check) {
    const existing = fs.existsSync(target.out) ? fs.readFileSync(target.out, "utf8") : "";
    if (existing !== code) {
      console.error(`${path.relative(root, target.out)} is out of date with its source. Run \`node plugin/build.mjs\`.`);
      outOfDate = true;
    } else {
      console.log(`${path.relative(root, target.out)} is up to date (${code.length} bytes)`);
    }
  } else {
    fs.mkdirSync(path.dirname(target.out), { recursive: true });
    fs.writeFileSync(target.out, code);
    console.log(`wrote ${path.relative(process.cwd(), target.out)} (${code.length} bytes)`);
  }
}

if (check && outOfDate) {
  process.exit(1);
}
