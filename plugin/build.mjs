#!/usr/bin/env node
// Bundles plugin/src/index.js into the single self-contained ESM file Buzz
// loads (plugin/plugin.js). Uses buzz-app's Rolldown, matching
// attention/build-core.mjs, memory/build-nip44.mjs, plugin/build-markdown.mjs,
// and plugin/build-novnc.mjs.
//
//   node plugin/build.mjs [--check] [path-to-buzz-app]
//
// Pass --check to verify plugin/plugin.js matches plugin/src/ without writing.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const check = args.includes("--check");
const appArg = args.find((a) => !a.startsWith("-"));
const app = path.resolve(appArg ?? process.env.BUZZ_APP ?? path.join(os.homedir(), "Work/buzz-app"));

const pnpm = path.join(app, "node_modules", ".pnpm");
if (!fs.existsSync(pnpm)) {
  throw new Error(`buzz-app node_modules not found at ${pnpm}; pass [path-to-buzz-app] or set BUZZ_APP`);
}
const rolldownDir = fs.readdirSync(pnpm).find((name) => /^rolldown@\d/.test(name));
if (!rolldownDir) throw new Error("buzz-app has no rolldown; run pnpm install there");
const { build } = await import(
  pathToFileURL(path.join(pnpm, rolldownDir, "node_modules/rolldown/dist/index.mjs")).href
);

const entry = path.join(here, "src", "index.js");
const out = path.join(here, "plugin.js");
const banner = [
  "// GENERATED by plugin/build.mjs from plugin/src/. Do not edit directly;",
  "// edit files under plugin/src/ and run `node plugin/build.mjs`.",
].join("\n");

const result = await build({
  input: entry,
  platform: "browser",
  treeshake: true,
  write: false,
  output: {
    format: "esm",
    codeSplitting: false,
    minify: false,
    banner,
  },
});

const code = result.output[0].code;
if (/\bfrom\s*["']\.?\.\//.test(code)) {
  throw new Error("bundled plugin.js still contains relative imports");
}

if (check) {
  const existing = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (existing !== code) {
    console.error("plugin/plugin.js is out of date with plugin/src/. Run `node plugin/build.mjs`.");
    process.exit(1);
  }
  console.log(`plugin/plugin.js is up to date (${code.length} bytes)`);
} else {
  fs.writeFileSync(out, code);
  console.log(`wrote ${path.relative(process.cwd(), out)} (${code.length} bytes)`);
}
