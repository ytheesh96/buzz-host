#!/usr/bin/env node
// Bundles noVNC's RFB client into plugin/src/generated/novnc-client.js, for
// the Desktop tab (an agent's desktop over buzz-host's /desktop WebSocket).
// Buzz loads a plugin as one file, so plugin/build.mjs inlines this module
// into plugin/plugin.js. Rerun to update, then run `node plugin/build.mjs`:
//
//   npm pack @novnc/novnc@1.7.0 && tar xzf novnc-novnc-1.7.0.tgz && mv package ~/Work/novnc
//   node plugin/build-novnc.mjs [path-to-novnc] [path-to-buzz-app]   defaults ~/Work/novnc, ~/Work/buzz-app
//
// Uses buzz-app's Rolldown, as build-markdown.mjs does.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const novnc = path.resolve(process.argv[2] ?? path.join(os.homedir(), "Work/novnc"));
const app = path.resolve(process.argv[3] ?? process.env.BUZZ_APP ?? path.join(os.homedir(), "Work/buzz-app"));
const { version, license } = JSON.parse(fs.readFileSync(path.join(novnc, "package.json"), "utf8"));

const pnpm = path.join(app, "node_modules", ".pnpm");
const rolldownDir = fs.readdirSync(pnpm).find((name) => /^rolldown@\d/.test(name));
if (!rolldownDir) throw new Error("buzz-app has no rolldown; run pnpm install there");
const { build } = await import(
  pathToFileURL(path.join(pnpm, rolldownDir, "node_modules/rolldown/dist/index.mjs")).href
);

const entry = path.join(os.tmpdir(), `buzz-host-novnc-entry-${process.pid}.mjs`);
fs.writeFileSync(entry, `export { default as RFB } from ${JSON.stringify(path.join(novnc, "core/rfb.js"))};\n`);
let code;
try {
  const result = await build({
    input: entry,
    platform: "browser",
    treeshake: true,
    write: false,
    plugins: [
      {
        // browser.js probes WebCodecs H.264 with a top-level await, which an
        // IIFE cannot hold. Xvnc never sends H.264, so the probe is "no".
        name: "no-h264-probe",
        transform(src, id) {
          if (!id.endsWith(path.join("core", "util", "browser.js"))) return null;
          const out = src.replace("await _checkWebCodecsH264DecodeSupport()", "false");
          if (out === src) throw new Error("noVNC's H.264 probe moved; update build-novnc.mjs");
          return { code: out };
        },
      },
    ],
    output: { format: "iife", name: "novncClient", minify: true, codeSplitting: false },
  });
  code = result.output[0].code.trim();
} finally {
  fs.rmSync(entry, { force: true });
}
if (/\bimport\s*\(|\brequire\(/.test(code)) throw new Error("the noVNC bundle still loads modules");
// Evaluated on first use (the Desktop tab), never when Buzz loads the plugin.
const PREFIX = "var novncClient=";
if (!code.startsWith(PREFIX)) throw new Error("unexpected bundle shape");
code = `export function novncClient() {\n  return (novncClient.loaded ??= (() => {\nreturn ${code.slice(PREFIX.length)}\n  })());\n}`;

const START = "// ---------- GENERATED by plugin/build-novnc.mjs";
const END = "// ---------- end GENERATED novnc ----------";
const outFile = path.join(here, "src", "generated", "novnc-client.js");
fs.mkdirSync(path.dirname(outFile), { recursive: true });
const section = [
  `${START}. Do not edit; rerun it. ----------`,
  `// noVNC ${version} RFB client (${license}, https://github.com/novnc/noVNC; source: ${novnc}).`,
  code,
  END,
].join("\n");
fs.writeFileSync(outFile, `${section}\n`);
console.log(`plugin/src/generated/novnc-client.js: noVNC ${version} RFB client (${code.length} bytes)`);
