#!/usr/bin/env node
// Bundles the Markdown parser Buzz renders an Interest's instructions with
// (react-markdown's remark-parse = mdast-util-from-markdown, plus remark-gfm's
// micromark-extension-gfm and mdast-util-gfm) into
// plugin/src/generated/markdown-parser.js, so the Attention tab parses
// instructions exactly as Buzz does. Rerun after a Buzz update, then run
// `node plugin/build.mjs`:
//
//   node plugin/build-markdown.mjs [path-to-buzz-app]     default ~/Work/buzz-app
//
// Uses the versions buzz-app installs and its own Rolldown.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(process.argv[2] ?? process.env.BUZZ_APP ?? path.join(os.homedir(), "Work/buzz-app"));
const commit = execFileSync("git", ["-C", app, "log", "-1", "--format=%h %cs"]).toString().trim();
const modules = path.join(app, "node_modules");

/** A package's directory as `from` (a package directory) resolves it under pnpm. */
const dep = (from, name) => {
  const dir = fs.realpathSync(path.join(from, "..", name));
  const { version } = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  return { dir, version, name };
};
const reactMarkdown = fs.realpathSync(path.join(modules, "react-markdown"));
const remarkGfm = fs.realpathSync(path.join(modules, "remark-gfm"));
const remarkParse = dep(reactMarkdown, "remark-parse");
const parts = [
  dep(remarkParse.dir, "mdast-util-from-markdown"),
  dep(remarkGfm, "micromark-extension-gfm"),
  dep(remarkGfm, "mdast-util-gfm"),
];
const [fromMarkdown, gfm, gfmMdast] = parts;

const pnpm = path.join(modules, ".pnpm");
const rolldownDir = fs.readdirSync(pnpm).find((name) => /^rolldown@\d/.test(name));
if (!rolldownDir) throw new Error("buzz-app has no rolldown; run pnpm install there");
const { build } = await import(
  pathToFileURL(path.join(pnpm, rolldownDir, "node_modules/rolldown/dist/index.mjs")).href
);

const entry = path.join(os.tmpdir(), `buzz-host-markdown-entry-${process.pid}.mjs`);
const file = (dir, rel) => JSON.stringify(path.join(dir, rel));
fs.writeFileSync(
  entry,
  `export { fromMarkdown } from ${file(fromMarkdown.dir, "index.js")};
export { gfm } from ${file(gfm.dir, "index.js")};
export { gfmFromMarkdown } from ${file(gfmMdast.dir, "index.js")};
`,
);
let code;
try {
  const result = await build({
    input: entry,
    // The browser builds, as Buzz's: entities decode through the DOM.
    platform: "browser",
    treeshake: true,
    write: false,
    output: { format: "iife", name: "markdownParser", minify: true, codeSplitting: false },
  });
  code = result.output[0].code.trim();
} finally {
  fs.rmSync(entry, { force: true });
}
if (/\bimport\s*\(|\brequire\(/.test(code)) throw new Error("the parser bundle still loads modules");
// Loaded on first use, not when Buzz evaluates the plugin module, which must
// stay pure (the parser's entity decoder makes a DOM element as it loads).
const PREFIX = "var markdownParser=";
if (!code.startsWith(PREFIX)) throw new Error("unexpected bundle shape");
code = `export function markdownParser() {\n  return (markdownParser.loaded ??= (() => {\nreturn ${code.slice(PREFIX.length)}\n  })());\n}`;

const START = "// ---------- GENERATED by plugin/build-markdown.mjs";
const END = "// ---------- end GENERATED ----------";
const outFile = path.join(here, "src", "generated", "markdown-parser.js");
fs.mkdirSync(path.dirname(outFile), { recursive: true });
const section = [
  `${START} from buzz-app ${commit}. Do not edit; rerun it. ----------`,
  `// Buzz's Markdown parser: ${parts.map((p) => `${p.name} ${p.version}`).join(", ")}`,
  "// (MIT, by Titus Wormer), as react-markdown and remark-gfm run it in Buzz.",
  code,
  END,
].join("\n");
fs.writeFileSync(outFile, `${section}\n`);
console.log(
  `plugin/src/generated/markdown-parser.js: Markdown parser from buzz-app ${commit} (${parts.map((p) => `${p.name}@${p.version}`).join(", ")}, ${code.length} bytes)`,
);
