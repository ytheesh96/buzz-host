#!/usr/bin/env node
// Bundles the NIP-44 v2 code Buzz's agent memory uses (nostr-tools/nip44, as
// buzz-app's src/buzz-mcp/node.ts imports it) into server/nip44.mjs, so
// buzz-host encrypts memory exactly as Buzz does.
//
//   node memory/build-nip44.mjs [path/to/buzz-app]   (needs `pnpm install` there)
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(process.argv[2] ?? path.join(os.homedir(), "Work/buzz-app"));
const pnpm = path.join(app, "node_modules/.pnpm");
const find = (re, what) => {
  const name = fs.readdirSync(pnpm).find((entry) => re.test(entry));
  if (!name) throw new Error(`buzz-app has no ${what}; run pnpm install there`);
  return name;
};
const nostr = find(/^nostr-tools@\d/, "nostr-tools");
const rolldown = find(/^rolldown@\d/, "rolldown");
const nip44 = path.join(pnpm, nostr, "node_modules/nostr-tools/lib/esm/nip44.js");
if (!fs.existsSync(nip44)) throw new Error(`missing ${nip44}`);
const { build } = await import(
  pathToFileURL(path.join(pnpm, rolldown, "node_modules/rolldown/dist/index.mjs")).href
);
const entry = path.join(path.dirname(nip44), `.buzz-host-nip44-${process.pid}.js`);
fs.writeFileSync(entry, `export { encrypt, decrypt, getConversationKey } from "./nip44.js";\n`);
const out = path.join(here, "../server/nip44.mjs");
try {
  await build({
    input: entry,
    platform: "node",
    treeshake: true,
    write: true,
    output: {
      file: out,
      format: "esm",
      codeSplitting: false,
      banner: `// GENERATED by memory/build-nip44.mjs from buzz-app's ${nostr.split("_")[0]}. Do not edit.\n// nostr-tools (Unlicense) and @noble (MIT): NIP-44 v2, as Buzz's agent memory uses it.`,
    },
  });
} finally {
  fs.rmSync(entry, { force: true });
}
console.log(`wrote ${path.relative(process.cwd(), out)} (${fs.statSync(out).size} bytes)`);
